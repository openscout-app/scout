import { expect, test } from 'bun:test';
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createBrokerDaemonTestHarness } from '../../runtime/src/test-helpers/broker-daemon-harness.test.ts';
import { RuntimeHttpClient } from './http-client.ts';
import { CoreHttpAdapter } from './core-http-mcp.ts';
import { localAdminProof } from './local-admin-proof.ts';
const broker = createBrokerDaemonTestHarness();
test('core HTTP adapter reaches a protected isolated broker and records real operator/work/reply mutations', async()=>{
  const controlHome=mkdtempSync(join(tmpdir(),'mesh-http-fixture-'));
  const preload=join(controlHome,'version-preload.ts'), versionFile=join(controlHome,'child-version');
  writeFileSync(preload,`import { writeFileSync } from 'node:fs';writeFileSync(${JSON.stringify(versionFile)},Bun.version);`);
  const h = await broker.startBroker({protectedLocal:true,controlHome,preload,startupTimeoutMs:15_000});
  expect(readFileSync(versionFile,'utf8')).toBe(Bun.version);
  const bare = new RuntimeHttpClient({brokerUrl:h.baseUrl});
  const card = await bare.request('/v1/node');
  const client = new RuntimeHttpClient({brokerUrl:h.baseUrl,proof:localAdminProof(h.localAdminKey!,card.card.keyId)});
  await expect(bare.request('/v1/snapshot')).rejects.toThrow('refused');
  const p = {kind:'oauth' as const,id:'test',ownerKey:'test-owner',node:'test-node',agentId:'test-sender'};
  const adapter = new CoreHttpAdapter({client,principal:p});
  const signal = await adapter.call('ask',{operator:true,fyi:true,body:'isolated test signal'});
  expect(signal.kind).toBe('delivery');
  const snapshot = await client.request('/v1/snapshot');
  const message = Object.values(snapshot.messages).find((m:any)=>m.body==='isolated test signal') as any;
  expect(message?.actorId).toBe(p.agentId);
  const reply = await adapter.call('reply',{body:'isolated follow-up',to:message.id});
  expect(reply).toBeDefined();
  const task = await adapter.call('ask',{operator:true,body:'Choose a deployment target',options:['staging','prod'],requestId:'operator-task'});
  const accepted = await client.request('/v1/snapshot');
  expect(accepted.invocations[task.ids.invocationId].metadata.humanOwned).toBe(true);
  expect(task.flightId).toBeDefined();
  await client.request('/v1/messages/reply',{ref:task.ids.invocationId,senderId:'operator',requestId:'operator-answer',body:'staging'});
  const finished = await adapter.call('invocations_wait',{flightId:task.flightId,timeoutSeconds:1});
  expect(finished.flight.state).toBe('completed');
  await broker.seedBasicConversation(h);
  const seeded = await client.request('/v1/snapshot');
  await client.request('/v1/agents',{...seeded.agents.fabric,id:'other-target',displayName:'Other target'});
  const group = await adapter.call('ask',{body:'one group message',channel:'explicit-test-group',fyi:true});
  const grouped = await client.request('/v1/snapshot');
  const groupMessage = grouped.messages[group.ids.messageId];
  expect(groupMessage.body).toBe('one group message');
  expect(groupMessage.audience).toBeDefined();
  expect(group.flightId).toBeUndefined();
  const now=Date.now();
  await client.request('/v1/collaboration/records',{id:'test-work',kind:'work_item',title:'Test work',state:'open',acceptanceState:'none',ownerId:p.agentId,nextMoveOwnerId:p.agentId,createdById:p.agentId,createdAt:now,updatedAt:now});
  const updated = await adapter.call('work_update',{work:{workId:'test-work',state:'working'}});
  expect(updated.workItem.state).toBe('working');
  const events = await client.request('/v1/collaboration/events?recordId=test-work');
  expect(events.some((e:any)=>e.kind==='claimed' && e.actorId===p.agentId)).toBe(true);
}, 30_000);
